#  LESSON ASSEMBLY  (shared by --once and --dry-run)
# --------------------------------------------------------------------------- #
def plan_lesson(progress):
    """Decide today's word mix from the queue + SRS state. Returns a dict of
    everything needed to generate and later record the lesson."""
    vocab = progress["vocab"]

    review_words = get_due_review_words(vocab, REVIEW_PER_DAY_TARGET)

    # your queued words first, in the order you added them
    added_words = [
        {"word": item["word"], "language": item["language"]}
        for item in progress["queue"][:WORDS_PER_DAY]
    ]

    # top up remaining slots with auto-generated German
    remaining = WORDS_PER_DAY - len(added_words)
    german_counts = {"A2": 0, "B1": 0, "B2": 0}
    for lvl in GERMAN_AUTO_SLOTS[:remaining]:
        german_counts[lvl] += 1

    known_words = [w for w, info in vocab.items() if info.get("language", "de") == "de"]
    grammar_topic = GRAMMAR_TOPICS[progress["grammar_index"] % len(GRAMMAR_TOPICS)]

    return {
        "german_counts": german_counts,
        "added_words": added_words,
        "review_words": review_words,
        "known_words": known_words,
        "grammar_topic": grammar_topic,
        "consumed_from_queue": len(added_words),
    }


def send_voice_notes(lesson):
    scripts = collect_scripts_by_language(lesson)
    for lang, text in scripts.items():
        if not text.strip():
            continue
        voice = VOICES.get(lang)
        if not voice:
            continue
        try:
            ogg_bytes = synthesize_voice(text, voice)
            caption = f"{LANG_FLAGS.get(lang, '')} {LANG_NAMES.get(lang, lang)}" if len(scripts) > 1 else None
            send_telegram_voice(ogg_bytes, caption=caption)
            print(f"Voice note sent ({lang}).")
        except Exception as e:
            # Non-fatal: a TTS/ffmpeg hiccup shouldn't block the text lesson.
            print(f"Voice note failed for {lang}, continuing: {e}")


