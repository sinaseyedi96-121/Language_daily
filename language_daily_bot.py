def load_progress():
    data = {"vocab": {}, "grammar_index": 0, "queue": [], "update_offset": 0}
    if os.path.exists(PROGRESS_FILE):
        try:
            with open(PROGRESS_FILE, "r", encoding="utf-8") as f:
                loaded = json.load(f)
            data.update(loaded)
        except (json.JSONDecodeError, OSError):
            pass
    data.setdefault("vocab", {})
    data.setdefault("grammar_index", 0)
    data.setdefault("queue", [])
    data.setdefault("update_offset", 0)
    # Migration: entries created before multi-language support have no language.
    for info in data["vocab"].values():
        info.setdefault("language", "de")
    return data


def save_progress(progress):
    with open(PROGRESS_FILE, "w", encoding="utf-8") as f:
        json.dump(progress, f, ensure_ascii=False, indent=2)


def compute_next_review_date(review_count):
    idx = min(review_count, len(REVIEW_INTERVALS) - 1)
    return (date.today() + timedelta(days=REVIEW_INTERVALS[idx])).isoformat()


def get_due_review_words(vocab, limit):
    """Return up to `limit` due words as {word, language} dicts."""
    today_iso = date.today().isoformat()
    due = [w for w, info in vocab.items() if info.get("next_review", "9999-12-31") <= today_iso]
    due.sort(key=lambda w: vocab[w].get("next_review", ""))
    return [{"word": w, "language": vocab[w].get("language", "de")} for w in due[:limit]]


def update_vocab_after_send(vocab, taught_items, review_items, requested_review):
    """Record newly-taught words and advance SRS state for reviewed ones."""
    today_iso = date.today().isoformat()

    for w in taught_items:
        key = (w.get("word") or "").strip()
        if not key or key in vocab:
            continue
        vocab[key] = {
            "language": w.get("language", "de"),
            "first_seen": today_iso,
            "review_count": 0,
            "next_review": compute_next_review_date(0),
        }

    returned = {(w.get("word") or "").strip() for w in review_items}
    for r in requested_review:
        key = r["word"]
        if key not in vocab:
            continue
        if key in returned:
            vocab[key]["review_count"] = vocab[key].get("review_count", 0) + 1
            vocab[key]["last_reviewed"] = today_iso
            vocab[key]["next_review"] = compute_next_review_date(vocab[key]["review_count"])
        # a requested review word the model didn't return keeps its due date,
        # so it simply comes up again next run instead of being lost

    return vocab


