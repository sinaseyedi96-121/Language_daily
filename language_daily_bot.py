def run_once():
    if not (TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID and ANTHROPIC_API_KEY):
        raise SystemExit(
            "Missing credentials. Set TELEGRAM_BOT_TOKEN, TELEGRAM_CHAT_ID, "
            "and ANTHROPIC_API_KEY in your .env file (local) or GitHub Secrets (cloud)."
        )

    progress = load_progress()

    # 1) read your DMs and queue any words you added since the last run
    ingest_user_words(progress)
    save_progress(progress)   # persist offset + queue before the heavier work

    # 2) plan today's mix (your words first, German top-up, due reviews)
    plan = plan_lesson(progress)
    mix = ", ".join(f"{n}x{lvl}" for lvl, n in plan["german_counts"].items() if n > 0) or "none"
    print(f"Added words: {len(plan['added_words'])}, German auto: {mix}, "
          f"reviews: {len(plan['review_words'])}, grammar: {plan['grammar_topic']}")

    lesson = generate_lesson(
        plan["german_counts"], plan["added_words"], plan["review_words"],
        plan["known_words"], plan["grammar_topic"],
    )

    # only trust review items that match something we actually asked to review
    review_keys = {(r["word"], r["language"]) for r in plan["review_words"]}
    review_items = [
        w for w in lesson.get("review_words", [])
        if ((w.get("word") or "").strip(), w.get("language", "de")) in review_keys
    ]
    missing = review_keys - {((w.get("word") or "").strip(), w.get("language", "de")) for w in review_items}
    if missing:
        print(f"Note: model skipped reviews for: {missing} (will retry next run)")
    lesson["review_words"] = review_items

    messages = build_messages(lesson)
    print(f"Sending {len(messages)} message(s) to Telegram...")
    for i, msg in enumerate(messages):
        send_telegram(msg)
        if i < len(messages) - 1:
            time.sleep(1)   # gentle pacing, avoids rate limits

    if ENABLE_VOICE:
        send_voice_notes(lesson)

    # 3) record state: newly-taught words enter the SRS store; consume the queue
    taught = lesson.get("new_words", [])
    update_vocab_after_send(progress["vocab"], taught, review_items, plan["review_words"])
    progress["queue"] = progress["queue"][plan["consumed_from_queue"]:]
    progress["grammar_index"] = (progress["grammar_index"] + 1) % len(GRAMMAR_TOPICS)
    save_progress(progress)

    print(f"Done. Vocab store: {len(progress['vocab'])} word(s). "
          f"Queue remaining: {len(progress['queue'])}. "
          f"Next grammar topic: {GRAMMAR_TOPICS[progress['grammar_index']]}")


def run_dry_run():
    """Build a sample lesson exercising all four languages, print it, send NOTHING.
    Uses the Anthropic API but never touches Telegram or progress.json."""
    if not ANTHROPIC_API_KEY:
        raise SystemExit("Dry run needs ANTHROPIC_API_KEY set (in .env).")

    added_words = [
        {"word": "frigorifero", "language": "it"},
        {"word": "食べる", "language": "ja"},
        {"word": "reliable", "language": "en"},
    ]
    remaining = WORDS_PER_DAY - len(added_words)
    german_counts = {"A2": 0, "B1": 0, "B2": 0}
    for lvl in GERMAN_AUTO_SLOTS[:remaining]:
        german_counts[lvl] += 1

    print(f"[dry-run] added={added_words}, german={german_counts}")
    lesson = generate_lesson(german_counts, added_words, [], [], GRAMMAR_TOPICS[0])

    print("\n===== TELEGRAM MESSAGES (not sent) =====\n")
    for msg in build_messages(lesson):
        print(msg)
        print("\n----- (message break) -----\n")

    scripts = collect_scripts_by_language(lesson)
    print("===== VOICE NOTES THAT WOULD BE SENT =====")
    for lang, text in scripts.items():
        print(f"\n[{lang}] voice={VOICES.get(lang)}\n{text}")
    print("\n[dry-run] Nothing was sent to Telegram; progress.json untouched.")


def run_scheduled():
    import schedule
    schedule.every().day.at(SEND_TIME).do(run_once)
    print(f"Scheduler running. Daily send at {SEND_TIME}. Ctrl+C to stop.")
    while True:
        schedule.run_pending()
        time.sleep(30)


