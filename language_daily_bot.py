def build_user_message(german_counts, added_words, review_words, known_words, grammar_topic):
    parts = []

    total_new_de = sum(n for n in german_counts.values() if n > 0)
    if total_new_de:
        breakdown = ", ".join(f"{n} at {lvl} level" for lvl, n in german_counts.items() if n > 0)
        parts.append(f"Generate {total_new_de} NEW German words I haven't seen before: {breakdown}.")
        if known_words:
            parts.append(
                "Do NOT reuse any of these already-covered German words: "
                + ", ".join(known_words)
            )

    if added_words:
        listed = ", ".join(f"{w['word']} ({LANG_NAMES.get(w['language'], w['language'])})" for w in added_words)
        parts.append(
            "Teach these specific words I added myself (keep the language I tagged; "
            "each item may be the word, its romaji, or an English meaning — teach "
            "the natural target-language word). Put them first in \"new_words\": " + listed
        )

    if review_words:
        listed = ", ".join(f"{w['word']} ({LANG_NAMES.get(w['language'], w['language'])})" for w in review_words)
        parts.append(
            "Also give fresh usage notes and 3 new example sentences for exactly "
            "these REVIEW words (use each word and language unchanged): " + listed
        )
    else:
        parts.append('No review words are due yet -- leave "review_words" as an empty list.')

    parts.append(f"German grammar tip topic for today: {grammar_topic}")

    if not total_new_de and not added_words:
        parts.append('No new words are needed today -- leave "new_words" as an empty list.')

    return "\n\n".join(parts)


