def _queue_summary(progress):
    q = progress.get("queue", [])
    if not q:
        return "Your queue is empty. Send me some words to learn!"
    lines = [f"📋 <b>{len(q)} word(s) queued</b> (taught in this order):"]
    for i, item in enumerate(q, 1):
        lines.append(f"{i}. {esc(item['word'])} {LANG_FLAGS.get(item['language'], '')}")
    return "\n".join(lines)


def handle_command(text, progress):
    cmd = text.strip().split()[0].lower().lstrip("/")
    cmd = cmd.split("@")[0]   # strip @botname suffix if present
    if cmd in ("start", "help"):
        send_telegram(HELP_TEXT, chat_id=ALLOWED_USER_ID)
    elif cmd in ("list", "queue"):
        send_telegram(_queue_summary(progress), chat_id=ALLOWED_USER_ID)


def ingest_user_words(progress):
    """Read new DMs from ALLOWED_USER_ID, queue any words, DM back a confirmation.

    Never raises — a Telegram hiccup here must not block the daily lesson.
    Returns the list of newly-queued (word, language) tuples.
    """
    try:
        updates = fetch_new_messages(progress.get("update_offset", 0))
    except Exception as e:
        print(f"Word ingestion skipped (getUpdates failed): {e}")
        return []

    existing = {(item["word"].lower(), item["language"]) for item in progress["queue"]}
    known_vocab = {w.lower() for w in progress["vocab"]}
    newly_queued, duplicates = [], []
    max_id = progress.get("update_offset", 0)

    for u in updates:
        max_id = max(max_id, u.get("update_id", 0))
        msg = u.get("message") or {}
        sender_id = (msg.get("from") or {}).get("id")
        if sender_id != ALLOWED_USER_ID:
            continue   # the bot reacts to nobody but you
        text = (msg.get("text") or "").strip()
        if not text:
            continue
        if text.startswith("/"):
            handle_command(text, progress)
            continue
        for word, lang in parse_added_words(text):
            key = (word.lower(), lang)
            if key in existing or word.lower() in known_vocab:
                duplicates.append((word, lang))
                continue
            existing.add(key)
            progress["queue"].append({
                "word": word, "language": lang, "added": date.today().isoformat()
            })
            newly_queued.append((word, lang))

    progress["update_offset"] = max_id

    if newly_queued:
        lines = ["✅ <b>Queued for your upcoming lessons:</b>"]
        lines += [f"• {esc(w)} {LANG_FLAGS.get(l, '')}" for w, l in newly_queued]
        if duplicates:
            dup = ", ".join(esc(w) for w, _ in duplicates)
            lines.append(f"\n<i>Skipped (already known/queued): {dup}</i>")
        try:
            send_telegram("\n".join(lines), chat_id=ALLOWED_USER_ID)
        except Exception as e:
            print(f"Could not send queue confirmation: {e}")
        print(f"Queued {len(newly_queued)} new word(s) from Telegram.")

    return newly_queued


