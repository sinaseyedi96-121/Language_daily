def _detect_lang(word, tagged):
    if JP_CHAR_RE.search(word):
        return "ja"
    return tagged


def _clean_headword(word, lang):
    """Strip a leading article from de/it nouns so the stored word is clean."""
    if lang == "it" and re.match(r"^l['’]\s*\S", word, flags=re.IGNORECASE):
        return re.sub(r"^l['’]\s*", "", word, flags=re.IGNORECASE).strip()
    tokens = word.split()
    if len(tokens) >= 2 and tokens[0].lower() in ARTICLES.get(lang, set()):
        return " ".join(tokens[1:]).strip()
    return word


def parse_added_words(text):
    """Parse one Telegram message into [(word, language), ...].

    Accepts tagged or plain lines, comma/newline separated, e.g.:
        it: frigorifero, lavatrice
        ja: 冷蔵庫
        reliable            (untagged -> German, unless it's Japanese script)
    """
    results = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        # optional leading "add:" / "add " prefix
        line = re.sub(r"^\s*add[:\s]+", "", line, flags=re.IGNORECASE)

        lang = DEFAULT_ADD_LANG
        m = re.match(r"^\s*(de|it|en|ja)\s*[:\-]\s*(.+)$", line, flags=re.IGNORECASE)
        if m:
            lang = m.group(1).lower()
            line = m.group(2)

        for chunk in re.split(r"[,;]|\s{2,}", line):
            word = chunk.strip().strip("•-–—*").strip()
            if word:
                detected = _detect_lang(word, lang)
                results.append((_clean_headword(word, detected), detected))
    return results


def fetch_new_messages(offset):
    url = TELEGRAM_API_BASE.format(token=TELEGRAM_BOT_TOKEN, method="getUpdates")
    params = {"timeout": 0, "allowed_updates": json.dumps(["message"])}
    if offset:
        params["offset"] = offset + 1
    resp = requests.get(url, params=params, timeout=30)
    resp.raise_for_status()
    return resp.json().get("result", [])


