def send_telegram(text, chat_id=None):
    url = TELEGRAM_API_BASE.format(token=TELEGRAM_BOT_TOKEN, method="sendMessage")
    payload = {
        "chat_id": chat_id or TELEGRAM_CHAT_ID,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    resp = requests.post(url, json=payload, timeout=30)
    resp.raise_for_status()
    return resp.json()


def send_telegram_voice(ogg_bytes, caption=None, chat_id=None):
    url = TELEGRAM_API_BASE.format(token=TELEGRAM_BOT_TOKEN, method="sendVoice")
    data = {"chat_id": chat_id or TELEGRAM_CHAT_ID}
    if caption:
        data["caption"] = caption
    files = {"voice": ("lesson.ogg", ogg_bytes, "audio/ogg")}
    resp = requests.post(url, data=data, files=files, timeout=60)
    resp.raise_for_status()
    return resp.json()


